#!/usr/bin/env python3
"""Builds supabase/seed.sql from supabase/seed/vehicles.json plus the defaults from the brief.

Usage: python3 scripts/build-seed.py
The seed is idempotent: re-running it does not duplicate or overwrite existing rows.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "supabase/seed/vehicles.json").read_text(encoding="utf-8"))


def q(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


out: list[str] = [
    "-- GENERATED by scripts/build-seed.py – do not edit by hand.",
    "-- Seed data for BTW Rental: categories, price tiers, vehicles imported once from",
    "-- btw.sk/nase-vozidla, extras, default location and settings.",
    "-- The owner account is created separately by scripts/seed-owner.ts (never in SQL).",
    "",
    "-- Categories",
]
for i, (slug, sk, en) in enumerate(
    [("sedan", "Sedan", "Sedan"), ("suv", "SUV", "SUV"), ("limousine", "Limousine", "Limousine"), ("van", "Van", "Van")], 1
):
    out.append(
        f"insert into public.vehicle_categories (slug, name, sort_order) values ({q(slug)}, {q({'sk': sk, 'en': en})}, {i * 10}) on conflict (slug) do nothing;"
    )

out += ["", "-- Price tiers (31+ days = individual price)"]
for lo, hi in [(1, 1), (2, 5), (6, 14), (15, 30), (31, None)]:
    out.append(f"insert into public.price_tiers (min_days, max_days) values ({lo}, {q(hi)}) on conflict (min_days) do nothing;")

out += ["", "-- Default location"]
out.append(
    "insert into public.locations (name, address, map_url, latitude, longitude, surcharge_cents, is_default, sort_order)\n"
    f"select {q({'sk': 'Bratislava – Trenčianska 56/A', 'en': 'Bratislava – Trenčianska 56/A'})}, 'Trenčianska 56/A, 821 09 Bratislava',\n"
    "       'https://www.google.com/maps/search/?api=1&query=Tren%C4%8Dianska+56%2FA%2C+Bratislava', null, null, 0, true, 10\n"
    " where not exists (select 1 from public.locations where is_default);"
)

out += ["", "-- Extras"]
extras = [
    ("roof_box", {"sk": "Strešný box", "en": "Roof box"}, 800, "per_day", 1),
    ("child_seat", {"sk": "Autosedačka", "en": "Child seat"}, 400, "per_day", 4),
    ("booster_seat", {"sk": "Podsedák", "en": "Booster seat"}, 200, "per_day", 4),
    ("second_driver", {"sk": "Druhý šofér", "en": "Additional driver"}, 500, "per_day", 1),
]
for i, (code, name, price, kind, max_q) in enumerate(extras, 1):
    out.append(
        "insert into public.extras (code, name, price_cents, pricing_type, max_quantity, is_global, sort_order)\n"
        f"values ({q(code)}, {q(name)}, {price}, {q(kind)}, {max_q}, true, {i * 10}) on conflict (code) do nothing;"
    )

out += ["", "-- Settings"]
settings = [
    # key, value, is_public
    ("company", {"name": "BY THE WAVE, s.r.o.", "address": "Trenčianska 56/A, 821 09 Bratislava", "ico": None, "dic": None, "ic_dph": None, "phone": None, "email": "btw@btw.sk", "web": "https://www.btw.sk"}, True),
    ("vat_rate", 23, True),
    ("operating_24_7", True, True),
    ("bank", {"iban": "SK00 0000 0000 0000 0000 0000", "swift": "XXXXSKBX", "account_name": "BY THE WAVE, s.r.o.", "is_placeholder": True}, False),
    ("payment_methods", ["transfer", "terminal", "cash"], True),
    ("payment_due_days", 3, False),
    ("min_lead_hours", 24, True),
    ("min_rental_days", 1, True),
    ("return_tolerance_minutes", 59, True),
    ("default_buffer_minutes", 240, False),
    ("individual_price_from_days", 31, True),
    ("cancellation_tiers", [{"min_hours": 72, "fee_percent": 0}, {"min_hours": 24, "fee_percent": 20}, {"min_hours": 0, "fee_percent": 100}], True),
    ("modification_deadline_hours", 48, True),
    ("deposit_cents", 100000, True),
    ("km_limit_per_day", 300, True),
    ("extra_km_cents", 62, True),
    ("min_driver_age", 21, True),
    ("min_license_months", 6, True),
    ("assistance", {"phone": "+421900000000", "insurer": None, "policy_number": None, "note": "nonstop"}, False),
    ("admin_notification_emails", ["btw@btw.sk"], False),
    ("email_from", "BY THE WAVE <info@rental.btw.sk>", False),
    ("email_reply_to", "btw@btw.sk", False),
    ("terms_version", "1", True),
    ("gdpr_version", "1", True),
    ("terms_url", "https://www.btw.sk/vseobecne-obchodne-podmienky", True),
    ("gdpr_url", "https://www.btw.sk/ochrana-osobnych-udajov", True),
    ("review_request_days", 3, False),
    ("google_review_url", None, False),
    ("timezone", "Europe/Bratislava", True),
]
for key, value, is_public in settings:
    out.append(
        f"insert into public.settings (key, value, is_public) values ({q(key)}, {q(json.dumps(value, ensure_ascii=False))}::jsonb, {q(is_public)}) on conflict (key) do nothing;"
    )

compact = []
for v in data["vehicles"]:
    compact.append(
        {
            **{k: v[k] for k in ("slug", "name", "brand", "model", "variant", "category", "license_plate", "vin", "engine",
                                 "power_kw", "power_hp", "gears", "drivetrain", "fuel", "transmission", "seats", "luggage",
                                 "sort_order", "price_per_day_cents", "features")},
            "description": {k: x for k, x in v["description"].items() if x},
            "images": [
                {"path": i["file"].removeprefix("images/"), "w": i["width"], "h": i["height"], "main": i["is_main"],
                 "role": i["role"], "sort": i["sort_order"] * 10}
                for i in v["images"]
            ],
        }
    )
payload = json.dumps(compact, ensure_ascii=False, separators=(",", ":"))
assert "$seed$" not in payload

out += [
    "",
    "-- Vehicles imported once from btw.sk/nase-vozidla (see supabase/seed/vehicles.json).",
    "-- VIN and licence plate are dummy test values; price is 79 EUR/day in every tier.",
    "create temp table _seed_vehicles as",
    f"select value as v from jsonb_array_elements($seed${payload}$seed$::jsonb);",
    """
-- Equipment catalogue: every distinct item, in first-seen order.
insert into public.features (group_key, name, sort_order)
select x.group_key, jsonb_build_object('sk', x.item), (row_number() over (order by x.first_seen))::integer * 10
  from (
    select g.key::public.feature_group as group_key, i.item, min(s.v ->> 'sort_order')::integer * 1000 + min(i.ord) as first_seen
      from _seed_vehicles s, jsonb_each(s.v -> 'features') g, jsonb_array_elements_text(g.value) with ordinality i(item, ord)
     group by 1, 2
  ) x
 where not exists (select 1 from public.features f where f.group_key = x.group_key and f.name ->> 'sk' = x.item);

insert into public.vehicles (slug, name, brand, model, variant, category_id, license_plate, vin, engine, power_kw, power_hp,
  gears, drivetrain, fuel, transmission, seats, luggage, description, sort_order)
select s.v ->> 'slug', s.v ->> 'name', s.v ->> 'brand', s.v ->> 'model', s.v ->> 'variant', c.id, s.v ->> 'license_plate',
       s.v ->> 'vin', s.v ->> 'engine', (s.v ->> 'power_kw')::integer, (s.v ->> 'power_hp')::integer, (s.v ->> 'gears')::integer,
       (s.v ->> 'drivetrain')::public.drivetrain_type, (s.v ->> 'fuel')::public.fuel_type,
       (s.v ->> 'transmission')::public.transmission_type, (s.v ->> 'seats')::integer, (s.v ->> 'luggage')::integer,
       s.v -> 'description', (s.v ->> 'sort_order')::integer
  from _seed_vehicles s
  join public.vehicle_categories c on c.slug = s.v ->> 'category'
on conflict (vin) do nothing;

insert into public.vehicle_prices (vehicle_id, tier_id, price_per_day_cents)
select v.id, t.id, (s.v ->> 'price_per_day_cents')::integer
  from _seed_vehicles s
  join public.vehicles v on v.vin = s.v ->> 'vin'
  cross join public.price_tiers t
 where t.max_days is not null
on conflict do nothing;

insert into public.vehicle_images (vehicle_id, storage_path, alt, width, height, sort_order, is_main)
select v.id, i ->> 'path',
       jsonb_build_object(
         'sk', v.name || ' – ' || case i ->> 'role' when 'exterior' then 'exteriér' else 'interiér' end,
         'en', v.name || ' – ' || (i ->> 'role')),
       (i ->> 'w')::integer, (i ->> 'h')::integer, (i ->> 'sort')::integer, (i ->> 'main')::boolean
  from _seed_vehicles s
  join public.vehicles v on v.vin = s.v ->> 'vin'
  cross join jsonb_array_elements(s.v -> 'images') i
 where not exists (select 1 from public.vehicle_images x where x.vehicle_id = v.id and x.storage_path = i ->> 'path');

insert into public.vehicle_features (vehicle_id, feature_id, sort_order)
select v.id, f.id, i.ord::integer * 10
  from _seed_vehicles s
  join public.vehicles v on v.vin = s.v ->> 'vin'
  cross join jsonb_each(s.v -> 'features') g
  cross join jsonb_array_elements_text(g.value) with ordinality i(item, ord)
  join public.features f on f.group_key = g.key::public.feature_group and f.name ->> 'sk' = i.item
on conflict do nothing;

drop table _seed_vehicles;""",
]

(ROOT / "supabase/seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"supabase/seed.sql written ({len(compact)} vehicles)")

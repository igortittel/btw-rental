// Generates lib/pdf/assets.generated.ts: the Montserrat subset (Latin + Latin Extended) and the
// logo paths used by the protocol PDF. Embedding them in a module keeps the PDF renderer
// independent of the file system layout of the serverless function.
//   node scripts/build-pdf-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const font = (weight) => readFileSync(new URL(`../assets/fonts/Montserrat-${weight}.ttf`, import.meta.url)).toString('base64')
const logo = readFileSync(new URL('../public/images/logo.svg', import.meta.url), 'utf8')
const paths = [...logo.matchAll(/<path d="([^"]+)" fill="([^"]+)"/g)].map((m) => ({ d: m[1], gradient: m[2].startsWith('url(') }))
if (paths.length !== 2) throw new Error(`logo.svg: expected 2 paths, found ${paths.length}`)

writeFileSync(
  new URL('../lib/pdf/assets.generated.ts', import.meta.url),
  `// GENERATED by scripts/build-pdf-assets.mjs – do not edit.
export const LOGO_VIEWBOX = '0 0 1000 901'
export const LOGO_PATHS: { d: string; gradient: boolean }[] = ${JSON.stringify(paths)}
export const MONTSERRAT_BASE64: Record<400 | 600 | 700, string> = {
  400: '${font('400Regular')}',
  600: '${font('600SemiBold')}',
  700: '${font('700Bold')}',
}
`,
)
